let currentLang = 'en';
function t(key) { return (LANGS[currentLang] || LANGS.en)[key] || LANGS.en[key] || key; }
function setLang(lang) {
  if (!LANGS[lang]) return;
  currentLang = lang;
  localStorage.setItem('srvctrl_lang', lang);
  applyTranslations();
}
function loadLang() {
  const saved = localStorage.getItem('srvctrl_lang');
  if (saved && LANGS[saved]) currentLang = saved;
  else {
    const browser = navigator.language.split('-')[0];
    if (LANGS[browser]) currentLang = browser;
  }
}
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.placeholder !== undefined && el.tagName === 'INPUT') el.placeholder = t(key);
    else el.textContent = t(key);
  });
}
